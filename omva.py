# -*- coding: utf-8 -*-
"""Нові розпорядження керівника Одеської міської військової адміністрації (ОМВА).

Джерело: https://omr.gov.ua/ua/acts/omva/ (перша сторінка = найновіші записи).

На відміну від розпоряджень мера, тут НЕМАЄ окремих категорій на кшталт
кадрових ("К") чи відряджень ("Вд") — перевірено на реальних даних
(omva.json, 224 записи за 5 місяців 2026 року): нумерація суцільна
("123-2026"), і жодних кадрових/відряджень серед них не знайшлось узагалі
(0 збігів навіть по розширених ключових словах). Зміст переважно —
"Про внесення змін", хід виконання програм, дозволи на землю, тарифи,
заходи воєнного стану.

Тому фільтр тут не потрібен: категорія відносно нечаста (~1-2 на добу
в середньому), і кожне нове розпорядження просто шлеться в канал без
відбору за ключовими словами — на прохання Лесі (за замовчуванням "все
скопом" тут не шум, бо це не сотні проєктів рішень, а сам факт нового
розпорядження керівника ОМВА).
"""
import sys, json
sys.stdout.reconfigure(encoding="utf-8")
import fetch
import scrape

PATH = "/ua/acts/omva/"


def fetch_latest():
    """Свіжий (без кешу) фетч першої сторінки — вміст змінюється щодня."""
    html_text = fetch.get(scrape.BASE + PATH)
    return scrape.parse_rows(html_text)


def latest_omva_orders():
    """Усі розпорядження керівника ОМВА серед найновіших записів, без фільтра."""
    return fetch_latest()


if __name__ == "__main__":
    events = latest_omva_orders()
    print(f"Знайдено {len(events)} розпоряджень ОМВА на першій сторінці:")
    print(json.dumps(events, ensure_ascii=False, indent=2))
