# -*- coding: utf-8 -*-
"""Скликання сесій Миколаївської міської ради.

Джерело: розпорядження міського голови (/documents/?c=4), відфільтровані
за ключовим словом "скликанн" у короткій назві документа — це відповідає
розпорядженням виду "Про скликання чергової/позачергової N сесії ...".

Такі розпорядження одночасно є і "покликанням на розпорядження", і містять
короткий порядок денний прямо в тексті (пункт "Розглянути на сесії: ..."),
тому окремого джерела порядку денного для сесій не треба — саме
розпорядження виконує обидві ролі, як і вимагалось (аналог sessions.py
для Одеси).

Примітка: серед збігів трапляються також розпорядження виду "Про
призначення дати продовження пленарного засідання ... сесії" — це
не скликання "з нуля", а перенесення/продовження вже призначеного
засідання. Вирішено залишати їх у стрічці: вони так само є подією
навколо сесії (зміна дати засідання), і журналістці корисно про
це знати.
"""
import sys, json
sys.stdout.reconfigure(encoding="utf-8")
import re
import mk_scrape

KEYWORD_RE = re.compile(r"скликанн", re.I)


def latest_sessions():
    rows = mk_scrape.fetch_latest(mk_scrape.CATEGORY_MAYOR)
    return [r for r in rows if KEYWORD_RE.search(r["description"] or "")]


if __name__ == "__main__":
    events = latest_sessions()
    print(f"Знайдено {len(events)} розпоряджень про скликання на першій сторінці:")
    print(json.dumps(events, ensure_ascii=False, indent=2))
